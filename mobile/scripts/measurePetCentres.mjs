// Measures where every pet form's art sits across its cell and writes
// src/components/petCentres.ts (see petCentring.ts for what it is used for).
//
//   PET_CENTRES_DUMP=/tmp/sheets.json npx jest petCentresDump
//   node scripts/measurePetCentres.mjs /tmp/sheets.json
//
// Sheets are read with pngjs; clips are decoded from their .webm copies with
// ffmpeg (libvpx, for the alpha). For each frame the art's middle is the
// midpoint of its silhouette's extent and its alpha-weighted mass, so a tail
// or a scarf counts without dominating; a clip's is the average over its frames.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { PNG } = createRequire(path.join(root, 'package.json'))('pngjs');
const forms = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const ALPHA = 40;
const round = (value) => Math.round(value * 1000) / 1000;

const middle = (alphaAt, x0, x1, y0, y1, step = 1) => {
  let mass = 0, sum = 0, min = Infinity, max = -Infinity;
  for (let y = y0; y < y1; y += step) for (let x = x0; x < x1; x += step) {
    const alpha = alphaAt(x, y);
    if (alpha < ALPHA) continue;
    mass += alpha; sum += alpha * x; min = Math.min(min, x); max = Math.max(max, x);
  }
  return mass ? ((min + max + step) / 2 + sum / mass) / 2 : null;
};

const sheets = new Map();
const entries = [];
for (const form of forms) {
  const file = path.join(root, form.source.split('mobile/')[1]);
  if (!sheets.has(file)) sheets.set(file, PNG.sync.read(fs.readFileSync(file)));
  const png = sheets.get(file);
  const cw = png.width / form.columns, ch = png.height / form.rows;
  const alphaAt = (x, y) => png.data[(y * png.width + x) * 4 + 3];

  const frames = {};
  for (const list of Object.values(form.animations)) {
    for (const [row, column] of list) {
      const key = `${row},${column}`;
      if (key in frames) continue;
      const x0 = Math.round(column * cw), y0 = Math.round(row * ch);
      const mid = middle(alphaAt, x0, Math.round(x0 + cw), y0, Math.round(y0 + ch));
      if (mid !== null) frames[key] = round(((mid - column * cw) / cw - 0.5) * form.artScale);
    }
  }

  const clips = {};
  for (const [animation, clip] of Object.entries(form.videos?.clips ?? {})) {
    const { frameSize: n, cell } = form.videos;
    const raw = execFileSync('ffmpeg', ['-v', 'error', '-c:v', 'libvpx-vp9', '-i', path.join(root, 'assets/pet/video', `${clip}.webm`),
      '-vf', `scale=${n}:${n}`, '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'], { maxBuffer: 2 ** 31 });
    const values = [];
    for (let start = 0; start + n * n * 4 <= raw.length; start += n * n * 4) {
      const mid = middle((x, y) => raw[start + (y * n + x) * 4 + 3], 0, n, 0, n, 2);
      if (mid !== null) values.push((mid - (cell.x + cell.size / 2)) / cell.size);
    }
    if (values.length) clips[animation] = round((values.reduce((a, b) => a + b, 0) / values.length) * form.artScale);
  }

  const clipText = Object.keys(clips).length
    ? `\n    clips: { ${Object.entries(clips).map(([k, v]) => `${k}: ${v}`).join(', ')} },`
    : '';
  entries.push(`  '${form.id}': {\n    frames: { ${Object.entries(frames).map(([k, v]) => `'${k}': ${v}`).join(', ')} },${clipText}\n  },`);
  console.log(form.id);
}

fs.writeFileSync(path.join(root, 'src/components/petCentres.ts'), `// Generated by scripts/measurePetCentres.mjs. Do not edit by hand: re-run it after
// changing a sheet, a clip or a frame map.
import type { PetAnimation } from './petSprites';

/**
 * Where each form's art actually sits across its cell, measured off the
 * pixels: for every sheet frame ("row,column") and every video clip, the
 * middle of the pet as a share of the window it is drawn in, positive to the
 * right. The art was not drawn centred -- the same bear leans left to idle and
 * right to sulk -- so the pet is moved back by this much (see petCentring.ts).
 * Keyed "breed" for a base form and "breed:build" for an evolution.
 */
export const PET_CENTRES: Record<string, { frames: Record<string, number>; clips?: Partial<Record<PetAnimation, number>> }> = {
${entries.join('\n')}
};
`);
