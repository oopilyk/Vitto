/**
 * Writes src/data/blockedTerms.ts: the content filter's lists as hashes.
 *
 *   node scripts/buildBlockedTerms.ts      (npm run build:blocked-terms)
 *
 * Reads the [severe] tier of src/data/offensiveWords.fixture.txt (slurs,
 * explicit sexual content, sexual-violence terms) and
 * src/data/allowedContaining.fixture.txt (ordinary words that contain one),
 * and writes each as its termHash, never as the word. Both fixtures stay in the
 * repo and out of the app: nothing the app imports reads them.
 *
 * Why: the app shipped the terms themselves, and App Review, reading the
 * strings in the binary, rejected it under guideline 1.1.1 for "severe
 * discriminatory language and hate speech" -- the very list that kept them out
 * of usernames and bios.
 *
 * The terms are split the way contentFilter.ts matches them, so it can hash
 * what someone typed the same way: short single words (matched whole), longer
 * single words (matched inside a word too; with the lengths to look for) and
 * phrases (matched as whole runs of words; with their word counts).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { termHash } from '../src/domain/termHash.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'src', 'data');

/** Matches contentFilter.ts: up to this many letters, a term only counts as a whole word. */
const SHORT_MAX = 4;

const lines = (file: string) =>
  readFileSync(join(DATA, file), 'utf8')
    .split('\n')
    .map((line) => line.trim());

const severe: string[] = [];
let tier: string | null = null;
for (const line of lines('offensiveWords.fixture.txt')) {
  const heading = /^\[(\w+)\]/.exec(line);
  if (heading) {
    tier = heading[1];
    continue;
  }
  if (!line || line.startsWith('#')) continue;
  if (tier === 'severe') severe.push(line.toLowerCase());
}
const allowed = lines('allowedContaining.fixture.txt').filter((line) => line && !line.startsWith('#'));
if (severe.length < 100 || allowed.length < 100) throw new Error(`Suspiciously short lists: ${severe.length} terms, ${allowed.length} allowed words.`);

const unique = <T,>(values: T[]) => [...new Set(values)];
const single = unique(severe.filter((term) => !term.includes(' ')));
const short = single.filter((term) => term.length <= SHORT_MAX);
const long = single.filter((term) => term.length > SHORT_MAX);
const phrases = unique(severe.filter((term) => term.includes(' ')));

const hashes = (terms: string[]) => unique(terms.map(termHash)).sort();
const list = (name: string, doc: string, values: readonly (string | number)[]) =>
  `/** ${doc} */\nexport const ${name}: readonly ${typeof values[0] === 'number' ? 'number' : 'string'}[] = [\n${values
    .map((value) => `  ${JSON.stringify(value)},`)
    .join('\n')}\n];\n`;

const out = `// GENERATED by scripts/buildBlockedTerms.ts -- do not edit; re-run it instead.
//
// The content filter's lists (see domain/contentFilter.ts), as termHash values:
// no term is written out here. Source: the [severe] tier of
// src/data/offensiveWords.fixture.txt, derived from "List of Dirty, Naughty,
// Obscene and Otherwise Bad Words" (LDNOOBW), English list, by Shutterstock,
// Inc., CC-BY-4.0, modified (see the fixture); and
// src/data/allowedContaining.fixture.txt (ENABLE word list, public domain).

${list('BLOCKED_SHORT', `Single-word terms of up to ${SHORT_MAX} letters: blocked as a whole word only.`, hashes(short))}
${list('BLOCKED_LONG', 'Longer single-word terms: blocked inside a word too.', hashes(long))}
${list('BLOCKED_LONG_LENGTHS', "The lengths of BLOCKED_LONG's terms.", unique(long.map((term) => term.length)).sort((a, b) => a - b))}
${list('BLOCKED_PHRASES', 'Phrases, single-spaced: blocked as a whole run of words.', hashes(phrases))}
${list('BLOCKED_PHRASE_WORDS', "How many words BLOCKED_PHRASES's phrases have.", unique(phrases.map((phrase) => phrase.split(' ').length)).sort((a, b) => a - b))}
${list('ALLOWED_CONTAINING', 'Ordinary words that contain a longer term ("therapist"): never blocked for it.', hashes(allowed))}`;

writeFileSync(join(DATA, 'blockedTerms.ts'), out);
console.log(`blockedTerms.ts: ${short.length} short, ${long.length} long, ${phrases.length} phrases, ${allowed.length} allowed.`);
